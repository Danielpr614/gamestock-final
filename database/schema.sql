CREATE DATABASE IF NOT EXISTS gamestock_final CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE gamestock_final;
CREATE TABLE usuarios (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(100) NOT NULL,email VARCHAR(150) NOT NULL UNIQUE,
 senha VARCHAR(255) NOT NULL,perfil ENUM('admin','cliente') NOT NULL DEFAULT 'cliente',ativo TINYINT NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CHECK (ativo IN (0,1))
) ENGINE=InnoDB;
CREATE TABLE clientes (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,usuario_id INT UNSIGNED NOT NULL UNIQUE,telefone VARCHAR(11) NOT NULL,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE categorias (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(50) NOT NULL UNIQUE,descricao VARCHAR(500) NOT NULL DEFAULT ''
) ENGINE=InnoDB;
CREATE TABLE games (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,categoria_id INT UNSIGNED NOT NULL,titulo VARCHAR(100) NOT NULL,
 descricao TEXT NOT NULL,preco DECIMAL(8,2) NOT NULL,estoque INT NOT NULL DEFAULT 0,imagem VARCHAR(255) NOT NULL DEFAULT '',
 plataforma ENUM('PC','PlayStation','Xbox','Nintendo') NOT NULL,sistemas VARCHAR(100) NOT NULL DEFAULT '',
 loja VARCHAR(100) NOT NULL DEFAULT '',link_loja VARCHAR(500) NOT NULL DEFAULT '',ativo TINYINT NOT NULL DEFAULT 1,
 preco_normal DECIMAL(8,2) NULL,preco_consultado DECIMAL(8,2) NULL,data_consulta DATE NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY titulo_plataforma(titulo,plataforma),FOREIGN KEY(categoria_id) REFERENCES categorias(id) ON DELETE RESTRICT,
 CHECK(preco>=0),CHECK(estoque BETWEEN 0 AND 1000000),CHECK(ativo IN (0,1))
) ENGINE=InnoDB;
CREATE TABLE pedidos (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,cliente_id INT UNSIGNED NOT NULL,
 status ENUM('rascunho','confirmado','concluido','cancelado') NOT NULL DEFAULT 'rascunho',total DECIMAL(12,2) NOT NULL DEFAULT 0,
 chave CHAR(64) NOT NULL UNIQUE,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(cliente_id) REFERENCES clientes(id) ON DELETE RESTRICT,CHECK(total>=0)
) ENGINE=InnoDB;
CREATE TABLE itens_pedido (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,pedido_id INT UNSIGNED NOT NULL,game_id INT UNSIGNED NOT NULL,
 titulo VARCHAR(100) NOT NULL,plataforma VARCHAR(20) NOT NULL,quantidade INT NOT NULL,preco_unitario DECIMAL(8,2) NOT NULL,
 UNIQUE KEY jogo_no_pedido(pedido_id,game_id),FOREIGN KEY(pedido_id) REFERENCES pedidos(id) ON DELETE CASCADE,
 FOREIGN KEY(game_id) REFERENCES games(id) ON DELETE RESTRICT,CHECK(quantidade BETWEEN 1 AND 99),CHECK(preco_unitario>=0)
) ENGINE=InnoDB;
